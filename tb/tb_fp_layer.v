`timescale 1ns/1ps

module tb_fp_layer;

    reg        clk;
    reg        rst_n;
    reg        valid_in;

    reg [31:0] x0;
    reg [31:0] x1;
    reg [31:0] x2;
    reg [31:0] x3;

    reg [31:0] w00, w01, w02, w03, bias0;
    reg [31:0] w10, w11, w12, w13, bias1;
    reg [31:0] w20, w21, w22, w23, bias2;
    reg [31:0] w30, w31, w32, w33, bias3;

    wire        valid_out;

    wire [31:0] y0;
    wire [31:0] y1;
    wire [31:0] y2;
    wire [31:0] y3;

    integer pass_count;
    integer fail_count;

    //----------------------------------------------------------
    // DUT
    //----------------------------------------------------------

    fp_layer dut (

        .clk       (clk),
        .rst_n     (rst_n),
        .valid_in  (valid_in),

        .x0        (x0),
        .x1        (x1),
        .x2        (x2),
        .x3        (x3),

        .w00       (w00),
        .w01       (w01),
        .w02       (w02),
        .w03       (w03),
        .bias0     (bias0),

        .w10       (w10),
        .w11       (w11),
        .w12       (w12),
        .w13       (w13),
        .bias1     (bias1),

        .w20       (w20),
        .w21       (w21),
        .w22       (w22),
        .w23       (w23),
        .bias2     (bias2),

        .w30       (w30),
        .w31       (w31),
        .w32       (w32),
        .w33       (w33),
        .bias3     (bias3),

        .valid_out (valid_out),

        .y0        (y0),
        .y1        (y1),
        .y2        (y2),
        .y3        (y3)

    );

    //----------------------------------------------------------
    // Clock
    //----------------------------------------------------------

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end

    //----------------------------------------------------------
    // Monitor
    //----------------------------------------------------------

    always @(posedge clk) begin

        #1;

        $display(
            "TIME=%0t | valid_in=%b | valid_out=%b",
            $time,
            valid_in,
            valid_out
        );

        if (valid_out) begin

            $display("    Neuron 0 = %h", y0);
            $display("    Neuron 1 = %h", y1);
            $display("    Neuron 2 = %h", y2);
            $display("    Neuron 3 = %h", y3);

        end

    end

    //----------------------------------------------------------
    // Test
    //----------------------------------------------------------

    initial begin

        rst_n    = 1'b0;
        valid_in = 1'b0;

        x0 = 32'b0;
        x1 = 32'b0;
        x2 = 32'b0;
        x3 = 32'b0;

        pass_count = 0;
        fail_count = 0;

        //------------------------------------------------------
        // Reset
        //------------------------------------------------------

        repeat (2)
            @(posedge clk);

        rst_n = 1'b1;

        //------------------------------------------------------
        // Input = [2,3,4,5]
        //------------------------------------------------------

        x0 = 32'h40000000;   // 2
        x1 = 32'h40400000;   // 3
        x2 = 32'h40800000;   // 4
        x3 = 32'h40A00000;   // 5

        //------------------------------------------------------
        // Neuron 0
        //
        // 2+3+4+5-5 = 9
        //------------------------------------------------------

        w00 = 32'h3F800000;
        w01 = 32'h3F800000;
        w02 = 32'h3F800000;
        w03 = 32'h3F800000;
        bias0 = 32'hC0A00000;

        //------------------------------------------------------
        // Neuron 1
        //
        // 2*2+3*2+4*2+5*2-5 = 23
        //------------------------------------------------------

        w10 = 32'h40000000;
        w11 = 32'h40000000;
        w12 = 32'h40000000;
        w13 = 32'h40000000;
        bias1 = 32'hC0A00000;

        //------------------------------------------------------
        // Neuron 2
        //
        // 2+3+4+5+1 = 15
        //------------------------------------------------------

        w20 = 32'h3F800000;
        w21 = 32'h3F800000;
        w22 = 32'h3F800000;
        w23 = 32'h3F800000;
        bias2 = 32'h3F800000;

        //------------------------------------------------------
        // Neuron 3
        //
        // 2+3+4+5-20 = -6
        // ReLU = 0
        //------------------------------------------------------

        w30 = 32'h3F800000;
        w31 = 32'h3F800000;
        w32 = 32'h3F800000;
        w33 = 32'h3F800000;
        bias3 = 32'hC1A00000;

        //------------------------------------------------------
        // Send transaction
        //------------------------------------------------------

        @(negedge clk);

        valid_in = 1'b1;

        @(posedge clk);

        #1;

        valid_in = 1'b0;

        //------------------------------------------------------
        // Wait for result
        //------------------------------------------------------

        wait (valid_out == 1'b1);

        #1;

        //------------------------------------------------------
        // Check y0
        //------------------------------------------------------

        if (y0 == 32'h41100000) begin
            $display("PASS: Neuron 0 = 9");
            pass_count = pass_count + 1;
        end
        else begin
            $display("FAIL: Neuron 0 = %h", y0);
            fail_count = fail_count + 1;
        end

        //------------------------------------------------------
        // Check y1
        //------------------------------------------------------

        if (y1 == 32'h41B80000) begin
            $display("PASS: Neuron 1 = 23");
            pass_count = pass_count + 1;
        end
        else begin
            $display("FAIL: Neuron 1 = %h", y1);
            fail_count = fail_count + 1;
        end

        //------------------------------------------------------
        // Check y2
        //------------------------------------------------------

        if (y2 == 32'h41700000) begin
            $display("PASS: Neuron 2 = 15");
            pass_count = pass_count + 1;
        end
        else begin
            $display("FAIL: Neuron 2 = %h", y2);
            fail_count = fail_count + 1;
        end

        //------------------------------------------------------
        // Check y3
        //------------------------------------------------------

        if (y3 == 32'h00000000) begin
            $display("PASS: Neuron 3 ReLU = 0");
            pass_count = pass_count + 1;
        end
        else begin
            $display("FAIL: Neuron 3 = %h", y3);
            fail_count = fail_count + 1;
        end

        //------------------------------------------------------
        // Summary
        //------------------------------------------------------

        $display("");
        $display("======================================");
        $display("FP32 LAYER TEST SUMMARY");
        $display("======================================");

        $display("PASS = %0d", pass_count);
        $display("FAIL = %0d", fail_count);

        if (fail_count == 0)
            $display("ALL TESTS PASSED");
        else
            $display("SOME TESTS FAILED");

        $display("======================================");

        #20;

        $finish;

    end

endmodule